"""PEP 517 build hook: 用 yun 预编译 SDK 构建 pybind11 扩展。

不再需要 yun 源码或 conan；SDK 由 yun 的 GitHub Release 提供。平台参数由
:mod:`sdk_platform` 统一决定，支持 macOS arm64、Linux x86_64/arm64、Windows x86_64。
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fetch_sdk import ensure_sdk  # noqa: E402
from sdk_platform import SdkPlatform, detect_platform  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "src" / "yunpyopt"
BUILD_DIR = ROOT / "build" / "yun-sdk-binding"
TARGET = "yun_python_binding"


def _run(cmd: list[str]) -> None:
    print("+", " ".join(str(part) for part in cmd), flush=True)
    subprocess.run(cmd, check=True)


def _pybind11_cmakedir() -> str:
    try:
        return subprocess.check_output(
            [sys.executable, "-m", "pybind11", "--cmakedir"],
            text=True,
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        raise SystemExit("需要 pybind11；它应由 PEP 517 build-system requires 安装。") from exc


def _cmake_configure_args(
    sdk: Path,
    build_dir: Path,
    spec: SdkPlatform,
    python: str,
    pybind11_dir: str | None = None,
) -> list[str]:
    args = [
        "cmake",
        "-S",
        str(sdk),
        "-B",
        str(build_dir),
        "-DCMAKE_BUILD_TYPE=Release",
        f"-DPython3_EXECUTABLE={python}",
        f"-Dpybind11_DIR={pybind11_dir or _pybind11_cmakedir()}",
        "-DCMAKE_SKIP_RPATH=ON",
    ]
    if spec.system == "darwin":
        args += [
            f"-DCMAKE_OSX_DEPLOYMENT_TARGET={os.environ.get('MACOSX_DEPLOYMENT_TARGET', '14.0')}",
            "-DCMAKE_OSX_ARCHITECTURES=arm64",
        ]
    elif spec.system == "linux":
        args.append("-DCMAKE_POSITION_INDEPENDENT_CODE=ON")
        cxx = os.environ.get("CXX")
        if cxx:
            args.append(f"-DCMAKE_CXX_COMPILER={cxx}")
        flags = "-static-libstdc++ -static-libgcc"
        args += [
            f"-DCMAKE_MODULE_LINKER_FLAGS={flags}",
            f"-DCMAKE_SHARED_LINKER_FLAGS={flags}",
        ]
    elif spec.system == "windows":
        args += [
            "-G",
            "Ninja",
            "-DCMAKE_C_COMPILER=clang-cl",
            "-DCMAKE_CXX_COMPILER=clang-cl",
            "-DCMAKE_MSVC_RUNTIME_LIBRARY=MultiThreadedDLL",
        ]
    return args


def _check_toolchain(spec: SdkPlatform) -> None:
    if shutil.which("cmake") is None:
        raise SystemExit("需要 cmake >= 3.24：brew install cmake / apt install cmake / choco install cmake")

    if spec.system == "linux":
        cxx = os.environ.get("CXX", "g++")
        try:
            version = subprocess.check_output([cxx, "-dumpfullversion"], text=True).strip()
        except (OSError, subprocess.CalledProcessError) as exc:
            raise SystemExit(f"需要 GCC 13.2+（当前 CXX={cxx}）") from exc
        major, minor = (int(part) for part in version.split(".")[:2])
        if (major, minor) < (13, 2):
            raise SystemExit(
                f"需要 GCC 13.2+（当前 {cxx} {version}）；manylinux 请先 source /opt/rh/gcc-toolset-14/enable"
            )
    elif spec.system == "windows":
        for tool in ("clang-cl", "ninja"):
            if shutil.which(tool) is None:
                raise SystemExit(f"需要 {tool}；请在 VS 2022 开发者环境中运行并安装 LLVM/Ninja")


def _write_build_info(sdk_version: str, spec: SdkPlatform) -> None:
    path = OUT_DIR / "_build_info.py"
    path.write_text(
        '"""Generated by scripts/build_ext.py. Do not edit."""\n\n'
        f'SDK_VERSION = "{sdk_version}"\n'
        f'SDK_PLATFORM = "{spec.tag}"\n',
        encoding="utf-8",
    )


def _smoke_import(target: Path) -> None:
    code = (
        "import importlib.util;"
        f"path = {str(target)!r};"
        "spec = importlib.util.spec_from_file_location('_core', path);"
        "mod = importlib.util.module_from_spec(spec);"
        "spec.loader.exec_module(mod);"
        "print('RESULT_KEYS', mod.RESULT_KEYS)"
    )
    _run([sys.executable, "-c", code])


def build() -> None:
    spec = detect_platform()
    _check_toolchain(spec)

    sdk = ensure_sdk(spec=spec)
    sdk_version = (sdk / "VERSION").read_text(encoding="utf-8").strip()

    if BUILD_DIR.exists():
        shutil.rmtree(BUILD_DIR)

    _run(_cmake_configure_args(sdk, BUILD_DIR, spec, sys.executable))
    _run(
        [
            "cmake",
            "--build",
            str(BUILD_DIR),
            "--target",
            TARGET,
            "--config",
            "Release",
            "-j",
            str(os.cpu_count() or 1),
        ]
    )

    modules = sorted(BUILD_DIR.glob(f"_core*{spec.extension_suffix}"))
    if len(modules) != 1:
        raise SystemExit(f"构建目录中应恰好有一个 _core*{spec.extension_suffix}，实际: {modules}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for pattern in ("_core.*.so", "_core.*.pyd"):
        for stale in OUT_DIR.glob(pattern):
            stale.unlink()
    target = OUT_DIR / modules[0].name
    shutil.copy2(modules[0], target)
    _write_build_info(sdk_version, spec)
    print(f"已复制扩展: {target}", flush=True)
    _smoke_import(target)


if __name__ == "__main__":
    build()
